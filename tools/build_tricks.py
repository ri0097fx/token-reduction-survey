#!/usr/bin/env python3
"""Usage: python3 -I tools/build_tricks.py"""
import csv
import os
import re

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPRO = os.path.join(ROOT, "repro")
MODELS = [("deit_tiny_patch16_224", "DeiT-T"), ("deit_small_patch16_224", "DeiT-S"), ("deit_base_patch16_224", "DeiT-B")]


def rows(name):
    return list(csv.DictReader(open(os.path.join(REPRO, name), newline="", encoding="utf-8")))


def model_of(note):
    for key, _ in MODELS:
        if key in note:
            return key
    if note.startswith("mae_"):
        return note.split(";")[0]
    return "deit_small_patch16_224"


def flips(a, b):
    x = np.load(os.path.join(REPRO, "preds", a + ".npy"))
    y = np.load(os.path.join(REPRO, "preds", b + ".npy"))
    return int((x != y).sum())


PROP_MODELS = [("deit_tiny_patch16_224", "DeiT-T"), ("deit_small_patch16_224", "DeiT-S"), ("deit_base_patch16_224", "DeiT-B"),
               ("mae_vit_base_patch16", "MAE-B"), ("mae_vit_large_patch16", "MAE-L"), ("mae_vit_huge_patch14", "MAE-H")]


def propattn(res):
    acc, base = {}, {}
    for r in rows("results_imagenet_v1.csv"):
        if r["method"] == "none":
            base[r["note"].split(".")[0] or "deit_small_patch16_224"] = (float(r["top1"]), float(r["gmacs"]))
    for r in res:
        if "fp" in r["note"] or "deterministic" in r["note"]:
            continue
        model = r["note"].split(";")[0]
        if not model.startswith(("deit_", "mae_")):
            model = "deit_small_patch16_224"
        if r["method"].startswith("none"):
            base.setdefault(model, (float(r["top1"]), float(r["gmacs"])))
        elif r["method"].startswith("tome"):
            m = re.match(r"r=(\d+)", r["setting"])
            if m:
                off = "no proportional" in r["setting"] or "without proportional" in r["setting"]
                acc[(model, int(m.group(1)), "off" if off else "on")] = (float(r["top1"]), float(r["gmacs"]))
    out = ["% generated by tools/build_tricks.py\n\\begin{small}\n\\setlength{\\tabcolsep}{5pt}\n",
           "\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n",
           " & & & & \\multicolumn{2}{c}{Proportional attention} \\\\\n\\cmidrule(l){5-6}\n",
           "Model & Unreduced & $r$ & GMACs & On & Off \\\\\n\\midrule\n"]
    quoted = {}
    for key, label in PROP_MODELS:
        rs = sorted({r for (m, r, _) in acc if m == key})
        for i, r in enumerate(rs):
            on, off = acc.get((key, r, "on")), acc.get((key, r, "off"))
            if on is None or off is None:
                continue
            best = max(on[0], off[0])
            cells = ["\\textbf{%.2f}" % v if v == best else "%.2f" % v for v in (on[0], off[0])]
            frac = "%.0f\\%%" % (100 * on[1] / base[key][1]) if key in base else "--"
            out.append("%s & %s & %d & %s & %s \\\\\n" % (label if i == 0 else "", ("%.2f" % base[key][0]) if i == 0 and key in base else "",
                                                     r, frac, " & ".join(cells)))
            quoted[(label, r)] = (on[0], off[0], frac)
    out.append("\\bottomrule\n\\end{tabular}\n\\end{small}\n")
    with open(os.path.join(ROOT, "paper", "tables", "tricks_propattn.tex"), "w") as fh:
        fh.write("".join(out))
    print("propattn:", quoted)


def precision(res):
    top1 = {}
    for r in res:
        m = r["method"].split()[0]
        d = "fp16" if "fp16" in r["note"] else "bf16" if "bf16" in r["note"] else "fp32"
        if "deterministic" in r["note"] or model_of(r["note"]) != "deit_small_patch16_224":
            continue
        key = {"none": "none", "tome": "tome_r13" if r["setting"].startswith("r=13") else None,
               "evit": "evit_0.7", "diffrate": "diffrate_2.9"}.get(m)
        if key and "matching in fp32" in r["setting"]:
            key, d = "tome_m32", d + "m32"
        if key:
            top1[(key, d)] = float(r["top1"])
    for r in rows("results_imagenet_precision.csv"):
        if r["method"].startswith("topk"):
            d = "fp16" if "fp16" in r["note"] else "bf16" if "bf16" in r["note"] else "fp32"
            top1[("topk_0.7", d)] = float(r["top1"])
    kl = {(r["model"], r["dtype"]): r for r in rows("results_imagenet_precision_kl.csv")}

    def klv(x):
        v = float(x) * 1e4
        return "%.0f" % v if v >= 10 else "%.1f" % v if v >= 1 else "%.2f" % v
    out = ["% generated by tools/build_tricks.py\n\\begin{small}\n\\setlength{\\tabcolsep}{5pt}\n",
           "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lrrrrrrr@{}}\n\\toprule\n",
           " & fp32 & \\multicolumn{3}{c}{fp16} & \\multicolumn{3}{c}{bf16} \\\\\n",
           "\\cmidrule(lr){3-5}\\cmidrule(l){6-8}\n",
           "Model & Top-1 & Top-1 & Changed & KL & Top-1 & Changed & KL \\\\\n",
           " & (\\%) & (\\%) & (images) & ($10^{-4}$ nats) & (\\%) & (images) & ($10^{-4}$ nats) \\\\\n\\midrule\n"]
    names = [("none", "none", "Unreduced DeiT-S"), ("topk_0.7", "topk_0.7", "Top-K, keep 0.7"),
             ("tome_r13", "tome_r13", "ToMe, $r = 13$"), ("diffrate_2.9", "diffrate_2.9", "DiffRate, 2.9 GFLOPs"),
             ("tome_m32", "tome_r13", "ToMe, $r = 13$, matching in fp32")]
    for key, kkey, label in names:
        sfx = "m32" if key == "tome_m32" else ""
        cells = [label, "--" if key == "tome_m32" else "%.2f" % top1[(key, "fp32")]]
        for d in ("fp16", "bf16"):
            r = kl[(kkey, d + sfx)]
            cells += ["%.2f" % top1[(key, d + sfx)], "{:,}".format(int(r["flips"])).replace(",", "{,}"), klv(r["kl_mean"])]
        out.append(" & ".join(cells) + " \\\\\n")
    out.append("\\bottomrule\n\\end{tabular*}\n\\end{small}\n")
    with open(os.path.join(ROOT, "paper", "tables", "tricks_precision.tex"), "w") as fh:
        fh.write("".join(out))
    print("precision:", {k: (v["flips"], v["kl_mean"]) for k, v in kl.items()})


def timing():
    sync = {r["variant"]: r for r in rows("bench_sync.csv")}
    comp = {r["method"]: r for r in rows("bench_compile.csv")}
    if os.path.exists(os.path.join(REPRO, "bench_compile_diffrate.csv")):
        comp.update({r["method"]: r for r in rows("bench_compile_diffrate.csv")})
    sdpa = {(r["method"], r["variant"], r["dtype"]): r for r in rows("bench_sdpa.csv")}

    def ms(v):
        return "%.2f" % float(v) if v not in (None, "") else "--"
    def thousands(v):
        return "{:,.0f}".format(float(v)).replace(",", "{,}")

    out = ["% generated by tools/build_tricks.py\n\\begin{small}\n\\setlength{\\tabcolsep}{4.5pt}\n",
           "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}llrrrr@{}}\n\\toprule\n",
           "Model & Implementation & \\multicolumn{3}{c}{GPU, batch 1 (ms)} & Batch 256 \\\\\n",
           "\\cmidrule(lr){3-5}\\cmidrule(l){6-6}\n",
           " & & Eager & Compiled & Graph & img/s \\\\\n\\midrule\n"]
    out.append("\\multicolumn{6}{@{}l}{\\textit{Synchronization inside the step (Top-K at blocks 4, 7, 10, fp32)}} \\\\*\n")
    for v, label in (("unreduced", "Unreduced DeiT-S"), ("gather", "topk and gather"), ("mask", "boolean-mask indexing"),
                     ("item", "count read with .item()")):
        r = sync[v]
        out.append("%s & %s & %s & -- & %s & %s \\\\\n" % ("DeiT-S" if v == "unreduced" else "", label, ms(r["ms_batch1"]),
                                                          ms(r["ms_batch1_cudagraph"]), thousands(r["img_per_s_batch256"])))
    out.append("\\midrule\n\\multicolumn{6}{@{}l}{\\textit{Released code in eager mode, compiled, and compiled into a CUDA graph (fp32)}} \\\\*\n")
    for m, label in (("none", "Unreduced DeiT-S"), ("evit", "EViT, keep 0.7"), ("tome", "ToMe, $r = 13$"), ("diffrate", "DiffRate, 2.9 GFLOPs")):
        r = comp.get(m)
        if r is None or r["eager_ms"].startswith("failed"):
            continue
        out.append("%s & released & %s & %s & %s & -- \\\\\n" % (label, ms(r["eager_ms"]), ms(r["default_ms"]), ms(r["reduce-overhead_ms"])))
    out.append("\\midrule\n\\multicolumn{6}{@{}l}{\\textit{Fused attention (SDPA), fp16 autocast}} \\\\*\n")
    for m, v, label in (("none", "released", "Unreduced DeiT-S"), ("none", "sdpa", ""), ("evit", "released", "EViT, keep 0.7"),
                        ("evit", "sdpa-clsrow", ""), ("tome", "released", "ToMe, $r = 13$"), ("tome", "sdpa-bias", ""),
                        ("tome", "sdpa-augment", "")):
        r = sdpa[(m, v, "fp16")]
        impl = {"released": "released (explicit attention matrix)", "sdpa": "SDPA", "sdpa-bias": "SDPA, $\\log s$ as additive mask",
                "sdpa-augment": "SDPA, $\\log s$ in an extra head dimension", "sdpa-clsrow": "SDPA, class row recomputed"}[v]
        out.append("%s & %s & %s & -- & -- & %s \\\\\n" % (label, impl, ms(r["ms_batch1"]), thousands(r["img_per_s_batch256"])))
    out.append("\\bottomrule\n\\end{tabular*}\n\\end{small}\n")
    with open(os.path.join(ROOT, "paper", "tables", "tricks_time.tex"), "w") as fh:
        fh.write("".join(out))
    for k, r in sdpa.items():
        print("sdpa", k, "diff", r["max_abs_diff"], "agree", r["pred_agreement"])


def main():
    res = rows("results_imagenet_tricks.csv")
    propattn(res)
    precision(res)
    timing()
    print("repeat flips:", flips("repeat1_tome_r13", "repeat2_tome_r13"), flips("repeat1_tome_r13", "repeat3_tome_r13"),
          flips("repeat1_evit_0.7", "repeat2_evit_0.7"), flips("repeat1_diffrate_2.9", "repeat2_diffrate_2.9"),
          "deterministic:", flips("det1_tome_r13", "det2_tome_r13"), flips("det1_tome_r13", "repeat1_tome_r13"))


if __name__ == "__main__":
    main()
