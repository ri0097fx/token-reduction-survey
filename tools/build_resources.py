#!/usr/bin/env python3
"""Usage: python3 -I tools/build_resources.py"""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPRO = os.path.join(ROOT, "repro")


METHODS = [
    ("topk", "Top-K", None, "Pruning"),
    ("evit", "EViT", "liang2022evit", "Pruning"),
    ("reprshift", "Representation Shift", "choi2025reprshift", "Pruning"),
    ("gtp", "GTP-ViT", "xu2024gtpvit", "Pruning"),
    ("ats", "ATS", "fayyaz2022ats", "Pruning"),
    ("papr", "PaPr", "mahmud2024papr", "Pruning"),
    ("tome", "ToMe", "bolya2023tome", "Merging and clustering"),
    ("mctf", "MCTF", "lee2024mctf", "Merging and clustering"),
    ("pitome", "PiToMe", "tran2024pitome", "Merging and clustering"),
    ("atc", "ATC", "haurum2024atc", "Merging and clustering"),
    ("diffrate", "DiffRate", "chen2023diffrate", "Hybrid"),
    ("ppt", "PPT", "wu2023ppt", "Hybrid"),
]

import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from venues import year_of
FAMILY_ORDER = ["Pruning", "Merging and clustering", "Hybrid"]
METHODS.sort(key=lambda m: (FAMILY_ORDER.index(m[3]), year_of(m[2]) if m[2] else 0))


def thousands(v):
    return "{:,}".format(int(round(float(v)))).replace(",", "{,}")


def read(name):
    path = os.path.join(REPRO, name)
    rows = {}
    for r in csv.DictReader(open(path, newline="", encoding="utf-8")):
        note = r.get("note", "")
        if "deit_tiny" in note or "deit_base" in note:
            continue
        rows[(r["method"].replace(" (official code)", ""), r["setting"])] = r
    return rows


def repeat_median(thr):
    import statistics
    path = os.path.join(REPRO, "resources_gpu_throughput_repeat.csv")
    if not os.path.exists(path):
        return thr
    runs = {}
    for r in csv.DictReader(open(path, newline="", encoding="utf-8")):
        runs.setdefault((r["method"].replace(" (official code)", ""), r["setting"]), []).append(float(r["img_per_s"]))
    for k, v in runs.items():
        if k in thr:
            thr[k] = dict(thr[k], img_per_s=str(statistics.median(v)))
    return thr


def main():
    thr, gl, cl = read("resources_gpu_throughput.csv"), read("resources_gpu_latency.csv"), read("resources_cpu_latency.csv")
    thr = repeat_median(thr)
    acc = read("results_imagenet_official.csv")
    base_t = float(thr[("none", "no reduction")]["img_per_s"])
    base_g, base_c = float(gl[("none", "no reduction")]["ms_batch1"]), float(cl[("none", "no reduction")]["ms_batch1"])
    base_a = acc[("none", "no reduction")]
    head = ("Method & GMACs & Top-1 & \\multicolumn{2}{c}{GPU, batch 256} & GPU, b.\\ 1 & CPU, b.\\ 1 \\\\\n"
            " & & (\\%) & img/s & MB & ms & ms \\\\\n")
    out = ["% generated by tools/build_resources.py, do not edit by hand\n",
           "\\begin{small}\n\\setlength{\\tabcolsep}{5pt}\n\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lrrrrrr@{}}\n\\toprule\n", head,
           "\\midrule\n",
           "Unreduced DeiT-S & %.2f & %.2f & %s & %s & %.2f & %.1f \\\\\n" % (
               float(base_a["gmacs"]), float(base_a["top1"]), thousands(base_t),
               thousands(float(thr[("none", "no reduction")]["peak_mb"])), base_g, base_c)]
    rows = []
    for mid, label, key, family in METHODS:
        settings = sorted({s for (m, s) in thr if m == mid and (m, s) in acc}, key=lambda s: -float(acc[(mid, s)]["gmacs"]))
        for s in settings:
            a = acc[(mid, s)]
            rows.append((family, label, key, float(a["gmacs"]), float(a["top1"]), float(thr[(mid, s)]["img_per_s"]),
                         float(thr[(mid, s)]["peak_mb"]), float(gl[(mid, s)]["ms_batch1"]), float(cl[(mid, s)]["ms_batch1"])))


    base_gmacs = float(base_a["gmacs"])
    level = [0 if abs(r[3] / base_gmacs - 0.65) < abs(r[3] / base_gmacs - 0.50) else 1 for r in rows]
    FMT = {4: "%.2f", 5: "%.0f", 6: "%.0f", 7: "%.2f", 8: "%.1f"}
    best = {}
    for lv in (0, 1):
        sub = [r for r, l in zip(rows, level) if l == lv]
        if sub:
            for j, higher in ((4, True), (5, True), (6, False), (7, False), (8, False)):
                best[(lv, j)] = sorted({float(FMT[j] % r[j]) for r in sub}, reverse=higher)[:2]

    def cell(text, lv, j, v):
        ranked = best.get((lv, j), [])
        v = float(FMT[j] % v)
        return text if v not in ranked else ("\\textbf{%s}" if v == ranked[0] else "\\underline{%s}") % text
    fam = None
    n = 0
    for r, lv in zip(rows, level):
        family, label, key, gmacs, top1, t, mb, gms, cms = r
        if family != fam:
            out.append("\\midrule\n\\multicolumn{7}{@{}l}{\\textit{%s}} \\\\*\n" % family)
            fam = family
        out.append("%s%s & %.2f & %s & %s & %s & %s & %s \\\\\n" % (
            label, "~\\cite{%s}" % key if key else "", gmacs, cell("%.2f" % top1, lv, 4, top1),
            cell("%s (%.2f$\\times$)" % (thousands(t), t / base_t), lv, 5, t),
            cell(thousands(mb), lv, 6, mb), cell("%.2f" % gms, lv, 7, gms), cell("%.1f" % cms, lv, 8, cms)))
        n += 1
    out.append("\\bottomrule\n\\end{tabular*}\n\\end{small}\n")
    with open(os.path.join(ROOT, "paper", "tables", "resources.tex"), "w", encoding="utf-8") as fh:
        fh.write("".join(out))
    print("rows:", n)


if __name__ == "__main__":
    main()
