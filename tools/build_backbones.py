"""Usage: python3 -I tools/build_backbones.py"""
import csv
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fig_style as S
from families import family_of_key
from venues import year_of

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV = os.path.join(ROOT, "repro", "results_imagenet_backbones.csv")

GROUPS = [
    ("Supervised on ImageNet-1k", [("deit_s", "DeiT-S", "DeiT-S"), ("t2t_14", "T2T-ViT-14", "T2T-14"), ("lvvit_s", "LV-ViT-S", "LV-ViT-S"),
                                   ("lvvit_m", "LV-ViT-M", "LV-ViT-M"), ("deit3_s", "DeiT III-S", "DeiT III-S"), ("deit3_b", "DeiT III-B", "DeiT III-B")]),
    ("Pre-trained on ImageNet-21k, fine-tuned", [("vit_b_orig", "ViT-B/16", "ViT-B/16"), ("augreg_s", "AugReg ViT-S", "AugReg-S"), ("augreg_b", "AugReg ViT-B", "AugReg-B")]),
    ("Masked image modeling, fine-tuned", [("beit_b", "BEiT-B", "BEiT-B"), ("eva02_s", "EVA-02-S (336 px)", "EVA02-S"), ("eva02_b", "EVA-02-B (448 px)", "EVA02-B")]),
    ("Self-supervised, linear head", [("dino_s", "DINO ViT-S", "DINO-S"), ("dino_b", "DINO ViT-B", "DINO-B"), ("dinov2_s", "DINOv2 ViT-S", "DINOv2-S"), ("dinov2_b", "DINOv2 ViT-B", "DINOv2-B")]),
    ("Language-supervised, fine-tuned", [("clip_b_openai", "CLIP ViT-B (OpenAI)", "CLIP-B (OAI)"), ("clip_b_laion", "CLIP ViT-B (LAION-2B)", "CLIP-B (LAION)")]),
]

METHOD_INFO = {
    "topk": ("Top-K", None), "evit": ("EViT", "liang2022evit"), "zero_tprune": ("Zero-TPrune", "wang2024zerotprune"),
    "tome": ("ToMe", "bolya2023tome"), "long_bat": ("BAT", "long2023beyond"), "mctf": ("MCTF", "lee2024mctf"),
    "atc": ("ATC", "haurum2024atc"), "pitome": ("PiToMe", "tran2024pitome"),
    "etps": ("eTPS", "wei2023tps"), "ppt": ("PPT", "wu2023ppt"), "tofu": ("ToFu", "kim2024tofu"),
}
FAMILY_ORDER = ["Pruning", "Merging and clustering", "Hybrid"]
TABLE_LABEL = {"zero_tprune": "ZTP"}
COL = "Z"


def method_columns(present):
    fam = family_of_key()
    cols = []
    for f in FAMILY_ORDER:
        ids = [m for m in present if m != "topk" and fam.get(METHOD_INFO[m][1]) == f]
        ids.sort(key=lambda m: year_of(METHOD_INFO[m][1]))
        if f == "Pruning" and "topk" in present:
            ids = ["topk"] + ids
        if ids:
            cols.append((f, ids))
    return cols


def load():
    rows = list(csv.DictReader(open(CSV, newline="", encoding="utf-8")))
    base, res = {}, {}
    for r in rows:
        if r["method"] == "none":
            base[r["backbone"]] = (float(r["top1"]), float(r["block_gmacs"]))
    for r in rows:
        b = r["backbone"]
        if r["method"] == "none" or b not in base:
            continue
        frac = float(r["block_gmacs"]) / base[b][1]
        level = 65 if frac > 0.575 else 50
        res[(b, r["method"], level)] = float(r["top1"])
    return base, res


def table(base, res):
    present = [m for m in METHOD_INFO if any(k[1] == m for k in res)]
    cols = method_columns(present)
    ids = [m for _, ms in cols for m in ms]
    n = len(ids) + 2
    out = ["% generated by tools/build_backbones.py\n\\begin{small}\n\\setlength{\\tabcolsep}{1pt}\n",
           "\\begin{tabularx}{\\linewidth}{@{}l%s%s@{}}\n\\toprule\n" % (COL, COL * len(ids))]

    head, start = [], 3
    for f, ms in cols:
        head.append("\\multicolumn{%d}{c}{%s}" % (len(ms), f))
    out.append(" & & " + " & ".join(head) + " \\\\\n")
    rules, c = [], 3
    for f, ms in cols:
        rules.append("\\cmidrule(lr){%d-%d}" % (c, c + len(ms) - 1))
        c += len(ms)
    out.append("".join(rules) + "\n")
    out.append("Backbone & Unred. & " + " & ".join(TABLE_LABEL.get(m, METHOD_INFO[m][0]) for m in ids) + " \\\\\n")
    for level in (65, 50):
        out.append("\\midrule\n\\multicolumn{%d}{@{}l}{\\textbf{%d\\%% of the block MACs}} \\\\*\n" % (n, level))
        for gi, (group, members) in enumerate(GROUPS):
            members = [m for m in members if m[0] in base]
            if not members:
                continue
            out.append("\\multicolumn{%d}{@{}l}{\\textit{%s}} \\\\*\n" % (n, group))
            for key, label, _ in members:
                vals = [res.get((key, m, level)) for m in ids]
                ranked = sorted({round(v, 1) for v in vals if v is not None}, reverse=True)[:2]
                cells = ["--" if v is None else ("\\textbf{%.1f}" if round(v, 1) == ranked[0] else
                         "\\underline{%.1f}" if round(v, 1) in ranked else "%.1f") % v for v in vals]
                out.append("%s & %.1f & %s \\\\\n" % (label, base[key][0], " & ".join(cells)))
    out.append("\\bottomrule\n\\end{tabularx}\n\\end{small}\n")
    with open(os.path.join(ROOT, "paper", "tables", "backbones.tex"), "w") as fh:
        fh.write("".join(out))
    return ids


def figure(base, res, ids):
    import numpy as np
    from matplotlib.colors import LinearSegmentedColormap
    S.apply()
    labels, keys = [], []
    for group, members in GROUPS:
        for key, _, short in members:
            if key in base:
                labels.append(short)
                keys.append(key)
    CAP = 10.0
    cmap = LinearSegmentedColormap.from_list("loss", ["#f7f9fb", "#b0c8e5", "#3a76bd", "#1c3557"])
    fig, axes = plt.subplots(2, 1, figsize=(S.TEXTWIDTH_IN, 4.9), sharex=True)
    fam = family_of_key()
    for ax, level in zip(axes, (65, 50)):
        loss = np.full((len(ids), len(keys)), np.nan)
        for i, m in enumerate(ids):
            for j, k in enumerate(keys):
                v = res.get((k, m, level))
                if v is not None:
                    loss[i, j] = base[k][0] - v
        im = ax.imshow(np.minimum(loss, CAP), cmap=cmap, vmin=0, vmax=CAP, aspect="auto", interpolation="nearest")
        for i in range(len(ids)):
            for j in range(len(keys)):
                if loss[i, j] >= CAP:
                    ax.text(j, i, "%.0f" % res[(keys[j], ids[i], level)], ha="center", va="center", fontsize=6.3, color="white")
        ax.set_yticks(range(len(ids)))
        ax.set_yticklabels([TABLE_LABEL.get(m, METHOD_INFO[m][0]) for m in ids], fontsize=7.5)
        ax.set_xticks(range(len(keys)))
        ax.grid(False)
        ax.tick_params(length=0)
        for sp in ax.spines.values():
            sp.set_visible(False)

        fams = [fam.get(METHOD_INFO[m][1]) if m != "topk" else "Pruning" for m in ids]
        for i in range(1, len(ids)):
            if fams[i] != fams[i - 1]:
                ax.axhline(i - 0.5, color="white", linewidth=2.0)
        pos = 0
        for group, members in GROUPS[:-1]:
            pos += sum(1 for mm in members if mm[0] in base)
            ax.axvline(pos - 0.5, color="white", linewidth=2.0)
        ax.set_title("(%s) %d%% of the block MACs" % ("ab"[level == 50], level), loc="left")
    axes[1].set_xticklabels(labels, rotation=60, ha="right", fontsize=7)
    fig.subplots_adjust(left=0.1, right=0.9, top=0.95, bottom=0.17, hspace=0.25)
    cax = fig.add_axes([0.915, 0.3, 0.013, 0.5])
    cb = fig.colorbar(im, cax=cax)
    cb.set_ticks([0, 2, 4, 6, 8, 10])
    cb.set_ticklabels(["0", "2", "4", "6", "8", "$\\geq$10"])
    cb.set_label("top-1 below the unreduced model (points)", fontsize=7.5)
    cb.outline.set_visible(False)
    cb.ax.tick_params(length=0, labelsize=7)
    S.save(fig, os.path.join(ROOT, "paper", "figures", "backbones"))


RES_ROWS = [("deit3_s", "DeiT III-S, 224 px", 197), ("deit3_s_384", "DeiT III-S, 384 px", 577), ("deit3_b", "DeiT III-B, 224 px", 197)]
RES_METHODS = ["topk", "tome", "mctf"]


def resolution():
    rows = list(csv.DictReader(open(CSV, newline="", encoding="utf-8")))
    base = {r["backbone"]: (float(r["top1"]), float(r["block_gmacs"])) for r in rows if r["method"] == "none"}
    val, gm = {}, {}
    for r in rows:
        b = r["backbone"]
        if r["method"] == "none" or b not in base:
            continue
        g = float(r["block_gmacs"])
        level = 65 if g / base[b][1] > 0.575 else 50
        val[(b, r["method"], level)] = float(r["top1"])
        if r["method"] == "tome":
            gm[(b, level)] = g
    cells = {}
    for key, _, _ in RES_ROWS:
        cells[(key, "none")] = "%.1f" % base[key][0]
        for level in (65, 50):
            for m in RES_METHODS:
                cells[(key, (m, level))] = "%.1f" % val[(key, m, level)]
    cols = ["none"] + [(m, level) for level in (65, 50) for m in RES_METHODS]
    best = {c: max(float(cells[(k, c)]) for k, _, _ in RES_ROWS) for c in cols}
    out = ["% generated by tools/build_backbones.py\n\\begin{small}\n\\setlength{\\tabcolsep}{4pt}\n",
           "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lrrrrrrrrrrr@{}}\n\\toprule\n",
           " & & \\multicolumn{2}{c}{Unreduced} & \\multicolumn{4}{c}{65\\% of the block MACs} & \\multicolumn{4}{c}{50\\% of the block MACs} \\\\\n",
           "\\cmidrule(lr){3-4}\\cmidrule(lr){5-8}\\cmidrule(l){9-12}\n",
           "Model & Tokens & GMACs & Top-1 & GMACs & Top-K & ToMe & MCTF & GMACs & Top-K & ToMe & MCTF \\\\\n\\midrule\n"]
    for key, label, tokens in RES_ROWS:
        def fmt(c):
            v = cells[(key, c)]
            return "\\textbf{%s}" % v if float(v) == best[c] else v
        line = [label, str(tokens), "%.1f" % base[key][1], fmt("none")]
        for level in (65, 50):
            line.append("%.1f" % gm[(key, level)])
            line += [fmt((m, level)) for m in RES_METHODS]
        out.append(" & ".join(line) + " \\\\\n")
    out.append("\\bottomrule\n\\end{tabular*}\n\\end{small}\n")
    with open(os.path.join(ROOT, "paper", "tables", "resolution.tex"), "w") as fh:
        fh.write("".join(out))


def main():
    base, res = load()
    ids = table(base, res)
    resolution()

    print("backbones:", len(base), "runs:", len(res), "methods:", ids)
    for key in base:
        for level in (65, 50):
            print("%-14s %d  unreduced %.2f  " % (key, level, base[key][0]) + "  ".join("%s %s" % (m, res.get((key, m, level))) for m in ids))


if __name__ == "__main__":
    main()
