#!/usr/bin/env python3
"""Usage: python3 -I tools/build_transfer.py"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_backbones import COL, METHOD_INFO, TABLE_LABEL, method_columns

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV = os.path.join(ROOT, "repro", "results_transfer_free.csv")
DATASETS = [("cub200", "CUB-200-2011"), ("cars", "Stanford Cars"), ("pets", "Oxford-IIIT Pets"),
            ("flowers", "Flowers-102"), ("indoor67", "MIT Indoor-67"), ("cifar10", "CIFAR-10"), ("cifar100", "CIFAR-100")]


def load():
    rows = list(csv.DictReader(open(CSV, newline="", encoding="utf-8")))
    base, res = {}, {}
    for r in rows:
        if r["method"] == "none":
            base[r["dataset"]] = (float(r["top1"]), float(r["block_gmacs"]))
    for r in rows:
        d = r["dataset"]
        if r["method"] == "none" or d not in base:
            continue
        level = 65 if float(r["block_gmacs"]) / base[d][1] > 0.575 else 50
        res[(d, r["method"], level)] = float(r["top1"])
    return base, res


def table(base, res):
    present = [m for m in METHOD_INFO if any(k[1] == m for k in res)]
    cols = method_columns(present)
    ids = [m for _, ms in cols for m in ms]
    n = len(ids) + 2
    out = ["% generated by tools/build_transfer.py\n\\begin{small}\n\\setlength{\\tabcolsep}{1pt}\n",
           "\\begin{tabularx}{\\linewidth}{@{}l%s%s@{}}\n\\toprule\n" % (COL, COL * len(ids))]
    out.append(" & & " + " & ".join("\\multicolumn{%d}{c}{%s}" % (len(ms), f) for f, ms in cols) + " \\\\\n")
    rules, c = [], 3
    for f, ms in cols:
        rules.append("\\cmidrule(lr){%d-%d}" % (c, c + len(ms) - 1))
        c += len(ms)
    out.append("".join(rules) + "\n")
    out.append("Dataset & Unred. & " + " & ".join(TABLE_LABEL.get(m, METHOD_INFO[m][0]) for m in ids) + " \\\\\n")
    for level in (65, 50):
        out.append("\\midrule\n\\multicolumn{%d}{@{}l}{\\textbf{%d\\%% of the block MACs}} \\\\*\n" % (n, level))
        for key, label in DATASETS:
            if key not in base:
                continue
            vals = [res.get((key, m, level)) for m in ids]
            ranked = sorted({round(v, 1) for v in vals if v is not None}, reverse=True)[:2]
            cells = ["--" if v is None else ("\\textbf{%.1f}" if round(v, 1) == ranked[0] else
                     "\\underline{%.1f}" if round(v, 1) in ranked else "%.1f") % v for v in vals]
            out.append("%s & %.1f & %s \\\\\n" % (label, base[key][0], " & ".join(cells)))
    out.append("\\bottomrule\n\\end{tabularx}\n\\end{small}\n")
    with open(os.path.join(ROOT, "paper", "tables", "transfer.tex"), "w") as fh:
        fh.write("".join(out))
    return ids


def main():
    base, res = load()
    ids = table(base, res)
    print("datasets:", len(base), "runs:", len(res), "methods:", ids)
    for key, _ in DATASETS:
        for level in (65, 50):
            print("%-9s %d  unreduced %.2f  " % (key, level, base[key][0]) + "  ".join("%s %s" % (m, res.get((key, m, level))) for m in ids))


if __name__ == "__main__":
    main()
